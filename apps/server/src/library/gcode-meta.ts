/**
 * Metadata from G-code comments written by slicers (PrusaSlicer, SuperSlicer,
 * OrcaSlicer, Bambu Studio, Cura). Only the head and tail of a file are read:
 * thumbnails and Cura's summary sit at the start, PrusaSlicer-style
 * summaries and settings at the end.
 */
export interface GcodeMeta {
  slicer: string | null;
  estimatedSeconds: number | null;
  filamentMm: number | null;
  filamentGrams: number | null;
  layerHeight: number | null;
  objectHeight: number | null;
  material: string | null;
  /** Largest embedded PNG/JPEG thumbnail. */
  thumbnail: { format: "png" | "jpg"; width: number; height: number; data: Buffer } | null;
}

/** "1d 2h 3m 4s" (PrusaSlicer/Orca) → seconds. */
export function parseDuration(text: string): number | null {
  let total = 0;
  let matched = false;
  for (const [, value, unit] of text.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    matched = true;
    total += Number(value) * { d: 86_400, h: 3_600, m: 60, s: 1 }[unit as "d" | "h" | "m" | "s"];
  }
  return matched ? Math.round(total) : null;
}

const number = (value: string | undefined) => {
  if (value === undefined) return null;
  // Multi-extruder slicers list one value per tool: "1234.5, 0"; sum them.
  const parts = value.split(/[,;]/).map((part) => Number.parseFloat(part.trim()));
  const valid = parts.filter(Number.isFinite);
  return valid.length ? valid.reduce((sum, part) => sum + part, 0) : null;
};

/** `; key = value` (PrusaSlicer family) or `;KEY:value` (Cura), case-insensitive key match. */
function lookup(lines: string[], pattern: RegExp): string | undefined {
  for (const line of lines) {
    const match = pattern.exec(line);
    if (match?.[1] !== undefined) return match[1].trim();
  }
  return undefined;
}

function thumbnails(text: string): GcodeMeta["thumbnail"] {
  // One linear pass over the lines (a single regex with a lazy body went
  // quadratic on files full of unmatched "begin" lines).
  let best: GcodeMeta["thumbnail"] = null;
  const begin = /^;\s*thumbnail(?:_(JPG|PNG))?\s+begin\s+(\d+)x(\d+)\s+\d+\s*$/i;
  const end = /^;\s*thumbnail(?:_(?:JPG|PNG))?\s+end/i;
  let current: { format: "jpg" | "png"; width: number; height: number; base64: string[] } | null =
    null;
  let blocks = 0;
  for (const raw of text.split("\n")) {
    const line = raw.endsWith("\r") ? raw.slice(0, -1) : raw;
    if (current) {
      if (end.test(line)) {
        const data = Buffer.from(current.base64.join(""), "base64");
        if (data.length > 0 && (!best || current.width * current.height > best.width * best.height))
          best = { format: current.format, width: current.width, height: current.height, data };
        current = null;
      } else current.base64.push(line.replace(/^;\s?/, "").replace(/\s+/g, ""));
      continue;
    }
    const match = begin.exec(line);
    if (!match) continue;
    if (++blocks > 16) break;
    current = {
      format: match[1]?.toUpperCase() === "JPG" ? "jpg" : "png",
      width: Number(match[2]),
      height: Number(match[3]),
      base64: [],
    };
  }
  return best;
}

export function parseGcodeMeta(head: string, tail: string): GcodeMeta {
  const lines = `${head}\n${tail}`.split(/\r?\n/).filter((line) => line.startsWith(";"));
  const generator = lookup(lines, /^;\s*generated by\s+(.+?)(?:\s+on\s+\d{4}-.*)?$/i);
  const cura = lookup(lines, /^;\s*Generated with\s+(.+)$/i);
  const slicer = (generator ?? cura)?.replace(/_SteamEngine/i, "") ?? null;

  const time =
    lookup(lines, /^;\s*estimated printing time(?:\s*\(normal mode\))?\s*=\s*(.+)$/i) ??
    lookup(lines, /^;\s*total estimated time\s*[:=]\s*(.+)$/i);
  const curaTime = lookup(lines, /^;TIME:(\d+(?:\.\d+)?)$/i);
  const filamentMm = number(lookup(lines, /^;\s*filament used \[mm\]\s*=\s*(.+)$/i));
  const curaMetres = lookup(lines, /^;\s*Filament used:\s*([\d.]+)\s*m/i);
  const filamentGrams =
    number(lookup(lines, /^;\s*(?:total\s+)?filament used \[g\]\s*=\s*(.+)$/i)) ??
    number(lookup(lines, /^;\s*filament used \[g\]\s*[:=]\s*(.+)$/i));
  const layerHeight =
    number(lookup(lines, /^;\s*layer_height\s*=\s*(.+)$/i)) ??
    number(lookup(lines, /^;\s*Layer height:\s*(.+)$/i));
  const objectHeight =
    number(lookup(lines, /^;\s*max_print_height\s*=\s*(.+)$/i)) ??
    number(lookup(lines, /^;MAXZ:(.+)$/i));
  const material = (
    lookup(lines, /^;\s*filament_type\s*=\s*(.+)$/i) ??
    lookup(lines, /^;\s*Filament type\s*[:=]\s*(.+)$/i)
  )
    ?.split(/[;,]/)[0]
    ?.trim();

  return {
    slicer,
    estimatedSeconds: time ? parseDuration(time) : curaTime ? Math.round(Number(curaTime)) : null,
    filamentMm: filamentMm ?? (curaMetres ? Number(curaMetres) * 1000 : null),
    filamentGrams,
    layerHeight,
    objectHeight,
    material: material || null,
    thumbnail: thumbnails(head),
  };
}
