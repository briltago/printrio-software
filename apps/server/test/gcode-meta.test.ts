import { describe, expect, it } from "vitest";
import { parseDuration, parseGcodeMeta } from "../src/library/gcode-meta.ts";

// 1×1 transparent PNG.
const PNG =
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==";
const thumb = (size: string) =>
  `; thumbnail begin ${size} ${PNG.length}\n; ${PNG.slice(0, 40)}\n; ${PNG.slice(40)}\n; thumbnail end\n`;

describe("parseDuration", () => {
  it("reads slicer durations", () => {
    expect(parseDuration("1h 37m 12s")).toBe(5832);
    expect(parseDuration("1d 2h 0m 5s")).toBe(93_605);
    expect(parseDuration("45m 3s")).toBe(2703);
    expect(parseDuration("soon")).toBeNull();
  });
});

describe("parseGcodeMeta", () => {
  it("reads PrusaSlicer / OrcaSlicer files", () => {
    const head = `; generated by OrcaSlicer 2.1.1 on 2026-10-20 at 10:00:00 UTC\n;\n${thumb("32x32")}${thumb("300x300")}G28\n`;
    const tail = [
      "; filament used [mm] = 1234.56",
      "; filament used [g] = 3.68",
      "; estimated printing time (normal mode) = 1h 37m 12s",
      "; layer_height = 0.2",
      "; max_print_height = 48",
      "; filament_type = PETG;PLA",
    ].join("\n");
    const meta = parseGcodeMeta(head, tail);
    expect(meta).toMatchObject({
      slicer: "OrcaSlicer 2.1.1",
      estimatedSeconds: 5832,
      filamentMm: 1234.56,
      filamentGrams: 3.68,
      layerHeight: 0.2,
      objectHeight: 48,
      material: "PETG",
    });
    expect(meta.thumbnail).toMatchObject({ format: "png", width: 300, height: 300 });
    expect(meta.thumbnail?.data.subarray(1, 4).toString()).toBe("PNG");
  });

  it("reads Cura files", () => {
    const head = [
      ";FLAVOR:Marlin",
      ";TIME:6666",
      ";Filament used: 2.5m",
      ";Layer height: 0.16",
      ";MAXZ:20.4",
      ";Generated with Cura_SteamEngine 5.7.0",
    ].join("\n");
    expect(parseGcodeMeta(head, "")).toMatchObject({
      slicer: "Cura 5.7.0",
      estimatedSeconds: 6666,
      filamentMm: 2500,
      filamentGrams: null,
      layerHeight: 0.16,
      objectHeight: 20.4,
      thumbnail: null,
    });
  });

  it("sums multi-tool values and tolerates unknown files", () => {
    const meta = parseGcodeMeta(
      "; generated by PrusaSlicer 2.8.0\n",
      "; filament used [mm] = 100.5, 20\n",
    );
    expect(meta.filamentMm).toBe(120.5);
    expect(parseGcodeMeta("G28\nG1 X10\n", "M84\n")).toEqual({
      slicer: null,
      estimatedSeconds: null,
      filamentMm: null,
      filamentGrams: null,
      layerHeight: null,
      objectHeight: null,
      material: null,
      thumbnail: null,
    });
  });

  it("stays fast on files full of unterminated thumbnail blocks", () => {
    const head = "; thumbnail begin 1x1 1\n".repeat(40_000);
    const started = performance.now();
    expect(parseGcodeMeta(head, "").thumbnail).toBeNull();
    expect(performance.now() - started).toBeLessThan(1000);
  });
});
