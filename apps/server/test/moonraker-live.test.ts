import type { PrinterStatus } from "@printrio/sdk";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { MoonrakerDriver } from "../src/drivers/moonraker.ts";

/**
 * Runs the Moonraker driver against a real Moonraker + Klipper, which the fake
 * in moonraker.test.ts cannot prove. Opt-in: set MOONRAKER_TEST_URL to a TEST
 * instance (e.g. Klipper with a host MCU and `kinematics: none`), never a
 * printer with hardware attached: this test starts, pauses and cancels a print
 * and triggers an emergency stop. The G-code only dwells (G4); nothing moves
 * or heats.
 */
const url = process.env.MOONRAKER_TEST_URL;
const apiKey = process.env.MOONRAKER_TEST_API_KEY;

const FILE = `printrio-live-test-${Date.now()}.gcode`;
const GCODE = [
  "; generated by PrusaSlicer 2.8.0",
  "; estimated printing time (normal mode) = 1m 0s",
  "; filament used [g] = 1.5",
  "; filament_type = PLA",
  ...Array.from({ length: 60 }, () => "G4 P1000"),
  "",
].join("\n");

describe.skipIf(!url)("Moonraker driver against a real Moonraker", () => {
  const driver = new MoonrakerDriver();
  let latest: PrinterStatus | null = null;

  const waitFor = async (predicate: (status: PrinterStatus) => boolean, timeoutMs = 20_000) => {
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
      const status = latest ?? (await driver.getStatus());
      if (predicate(status)) return status;
      await new Promise((resolve) => setTimeout(resolve, 250));
      latest = await driver.getStatus();
    }
    throw new Error(`Timed out; last state ${latest?.state} (${latest?.message ?? ""})`);
  };

  beforeAll(async () => {
    await driver.connect({ url: url as string, apiKey });
    driver.onStatus((status) => {
      latest = status;
    });
  });

  afterAll(async () => {
    await driver.deleteFile(FILE).catch(() => {});
    await driver.disconnect();
  });

  it("connects and reports a ready Klipper as idle", async () => {
    const info = await driver.getInfo();
    expect(info.firmwareState).toBe("ready");
    expect((await waitFor((s) => s.state === "idle")).state).toBe("idle");
  });

  it("uploads G-code and lists it with slicer metadata", async () => {
    await driver.uploadFile(FILE, new Blob([GCODE], { type: "text/x-gcode" }));
    const listing = await driver.listFiles("");
    const file = listing.files.find((entry) => entry.path === FILE);
    expect(file).toBeDefined();
    expect(file?.size).toBe(GCODE.length);
  });

  it("starts, pauses, resumes and cancels a print", async () => {
    await driver.startPrint(FILE);
    const printing = await waitFor((s) => s.state === "printing");
    expect(printing.job?.fileName).toBe(FILE);
    await driver.pause();
    await waitFor((s) => s.state === "paused");
    await driver.resume();
    await waitFor((s) => s.state === "printing");
    await driver.cancel();
    await waitFor((s) => s.state === "idle");
  });

  it("records the cancelled print in the history", async () => {
    const { jobs } = await driver.listJobs(5, 0);
    expect(jobs.find((job) => job.fileName === FILE)?.status).toBe("cancelled");
  });

  it("reports an emergency stop as an error and recovers with a firmware restart", async () => {
    await driver.emergencyStop();
    const stopped = await waitFor((s) => s.state === "error");
    expect(stopped.message).toBeTruthy();
    await driver.restartFirmware(true);
    await waitFor((s) => s.state === "idle", 30_000);
  });

  it("rejects starting a file that does not exist", async () => {
    await expect(driver.startPrint("does-not-exist.gcode")).rejects.toThrow();
    expect((await driver.getStatus()).state).toBe("idle");
  });

  it("deletes the uploaded file", async () => {
    await driver.deleteFile(FILE);
    expect((await driver.listFiles("")).files.some((entry) => entry.path === FILE)).toBe(false);
  });
});
