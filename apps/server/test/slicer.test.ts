import type { QueueItemDto } from "@printrio/shared";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { FakeMoonraker } from "../dev/fake-moonraker.ts";
import { createTestApp, sessionCookie } from "./helpers.ts";

let ctx: Awaited<ReturnType<typeof createTestApp>>;
let admin: string;
let key: string;
let printerId: string;
let fake: FakeMoonraker;

const api = (
  method: "GET" | "POST" | "DELETE" | "PUT",
  url: string,
  payload?: object,
  cookie = admin,
) => ctx.app.inject({ method, url, payload, headers: { cookie } });

/** What PrusaSlicer/OrcaSlicer send: OctoPrint form fields before the file. */
function slicerUpload(target: string, name: string, fields: Record<string, string>, apiKey = key) {
  const boundary = "----slicer";
  const parts = Object.entries(fields).map(
    ([field, value]) =>
      `--${boundary}\r\nContent-Disposition: form-data; name="${field}"\r\n\r\n${value}\r\n`,
  );
  return ctx.app.inject({
    method: "POST",
    url: `/octoprint/${target}/api/files/local`,
    headers: { "x-api-key": apiKey, "content-type": `multipart/form-data; boundary=${boundary}` },
    payload: `${parts.join("")}--${boundary}\r\nContent-Disposition: form-data; name="file"; filename="${name}"\r\nContent-Type: application/octet-stream\r\n\r\n; generated by PrusaSlicer 2.8.0\nG28\n\r\n--${boundary}--\r\n`,
  });
}

async function until<T>(read: () => Promise<T>, done: (value: T) => boolean): Promise<T> {
  for (let i = 0; i < 200; i++) {
    const value = await read();
    if (done(value)) return value;
    await new Promise((r) => setTimeout(r, 20));
  }
  throw new Error("Timed out waiting for a condition.");
}
const state = async () => (await api("GET", "/api/printers")).json().printers[0].status.state;
const queue = async (): Promise<QueueItemDto[]> =>
  (await api("GET", `/api/printers/${printerId}/queue`)).json().items;

beforeAll(async () => {
  ctx = await createTestApp();
  const setup = await ctx.app.inject({
    method: "POST",
    url: "/api/setup",
    payload: {
      email: "admin@example.com",
      displayName: "Admin",
      password: "correct horse battery",
    },
  });
  admin = sessionCookie(setup.headers["set-cookie"]);
  fake = new FakeMoonraker({ tickMs: 0, progressPerTick: 1 });
  await fake.start();
  printerId = (await api("POST", "/api/printers", { name: "Slicer", url: fake.url })).json().id;
  await until(state, (value) => value === "idle");
});

afterAll(async () => {
  await ctx.close();
  await fake.stop();
});

describe("API keys", () => {
  it("creates keys shown once and lists them by prefix", async () => {
    const created = await api("POST", "/api/api-keys", { name: "Workshop PC" });
    expect(created.statusCode).toBe(201);
    key = created.json().key;
    expect(key).toMatch(/^prk_/);
    const keys = (await api("GET", "/api/api-keys")).json().keys;
    expect(keys).toHaveLength(1);
    expect(keys[0]).toMatchObject({
      name: "Workshop PC",
      prefix: key.slice(0, 8),
      lastUsedAt: null,
    });
    expect(JSON.stringify(keys)).not.toContain(key);
    expect((await api("POST", "/api/api-keys", { name: " " })).statusCode).toBe(400);
  });
});

describe("OctoPrint-compatible upload", () => {
  it("answers the slicer's connection test only with a valid key", async () => {
    const ok = await ctx.app.inject({
      method: "GET",
      url: "/octoprint/library/api/version",
      headers: { "x-api-key": key },
    });
    expect(ok.json().text).toContain("OctoPrint");
    expect((await api("GET", "/api/api-keys")).json().keys[0].lastUsedAt).not.toBeNull();
    const query = await ctx.app.inject({
      method: "GET",
      url: `/octoprint/${printerId}/api/version?apikey=${key}`,
    });
    expect(query.statusCode).toBe(200);
    const bad = await ctx.app.inject({
      method: "GET",
      url: "/octoprint/library/api/version",
      headers: { "x-api-key": "prk_wrong" },
    });
    expect(bad.statusCode).toBe(401);
    const unknown = await ctx.app.inject({
      method: "GET",
      url: "/octoprint/00000000-0000-4000-8000-000000000000/api/version",
      headers: { "x-api-key": key },
    });
    expect(unknown.statusCode).toBe(404);
  });

  it("uploads into the library, into a folder", async () => {
    const res = await slicerUpload("library", "bracket.gcode", {
      path: "/Slicer/",
      print: "false",
    });
    expect(res.statusCode).toBe(201);
    expect(res.json()).toMatchObject({
      done: true,
      files: { local: { path: "Slicer/bracket.gcode" } },
    });
    const listing = (await api("GET", "/api/library?dir=Slicer")).json();
    expect(listing.files[0]).toMatchObject({
      name: "bracket.gcode",
      uploadedBy: "Admin",
      slicer: "PrusaSlicer 2.8.0",
    });
    expect((await slicerUpload("library", "evil.sh", {})).statusCode).toBe(415);
    expect((await slicerUpload("library", "x.gcode", {}, "nope")).statusCode).toBe(401);
  });

  it("prints on an idle printer and queues while it is busy", async () => {
    const first = await slicerUpload(printerId, "first.gcode", { print: "true" });
    expect(first.json().effectivePrint).toBe(true);
    expect(fake.uploads).toContain("first.gcode");
    await until(state, (value) => value === "printing");

    const second = await slicerUpload(printerId, "second.gcode", { print: "true" });
    expect(second.json().effectivePrint).toBe(false);
    const items = await queue();
    expect(items).toMatchObject([{ path: "second.gcode", source: "library", addedBy: "Admin" }]);

    fake.tick();
    await until(state, (value) => value === "idle");
    const started = await api("POST", `/api/printers/${printerId}/queue/start`);
    expect(started.json().started).toBe("second.gcode");
    expect(fake.uploads).toContain("second.gcode");
    await until(state, (value) => value === "printing");
    fake.tick();
    await until(state, (value) => value === "idle");

    const uploadOnly = await slicerUpload(printerId, "third.gcode", { print: "false" });
    expect(uploadOnly.json().effectivePrint).toBe(false);
    expect(fake.uploads).toContain("third.gcode");
    expect(await queue()).toEqual([]);
  });

  it("queues library files on a printer from the app", async () => {
    const res = await api("POST", `/api/printers/${printerId}/queue`, {
      path: "Slicer/bracket.gcode",
      source: "library",
    });
    expect(res.statusCode).toBe(201);
    const missing = await api("POST", `/api/printers/${printerId}/queue`, {
      path: "nope.gcode",
      source: "library",
    });
    expect(missing.statusCode).toBe(404);
    const started = await api("POST", `/api/printers/${printerId}/queue/start`);
    expect(started.json().started).toBe("Slicer/bracket.gcode");
    expect(fake.uploads).toContain("bracket.gcode");
  });

  it("revokes keys", async () => {
    const [entry] = (await api("GET", "/api/api-keys")).json().keys;
    expect((await api("DELETE", `/api/api-keys/${entry.id}`)).statusCode).toBe(204);
    const res = await ctx.app.inject({
      method: "GET",
      url: "/octoprint/library/api/version",
      headers: { "x-api-key": key },
    });
    expect(res.statusCode).toBe(401);
  });
});
